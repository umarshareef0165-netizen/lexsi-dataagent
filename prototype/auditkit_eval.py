"""Real AuditKIT + AgentTune integration for DataAgent (Lexsi Track 3 No. 6).

What this does, honestly:
1. Runs the DataAgent ``base`` and ``improved`` variants over the same 12
   tasks and records every run as a real AgentTune
   :class:`agenttune.agentic.trajectory.dataset.Trajectory` (one Step per
   tool call, ``action={"name", "arguments"}``, ``observation`` = the rows
   returned, ``final_response`` = the answer, ``reward`` = 1.0/0.0 by the
   same must-contain check the existing harness uses). Written to
   ``outputs/trajectories.jsonl`` via ``Trajectory.to_dict()`` — the portable
   JSONL record AuditKIT's ``episodes_from_agenttune`` reads.
2. Scores those recorded trajectories with the real AuditKIT
   ``AgentEvalRunner`` in ``recorded`` mode: each task becomes an
   ``AgentCase`` whose outcome oracle is a ``CustomPredicate`` checking the
   task's ``must_contain`` strings in the final answer (exactly the
   existing harness's correctness rule), plus the reference-free / name-only
   tool-call scorers against the documented minimal correct route
   (list_tables -> describe_table -> run_query). Results go to
   ``outputs/auditkit_eval.json``.

What this does NOT do (and must never be described as doing):
- No fine-tuning of Tiny Aya / Aya Expanse or any other model. No model
  weights were trained, no GPU was used, no HF credits were redeemed, no
  paid API was called. The "base vs improved" numbers are an AGENT
  comparison (naive tool use vs structured tool use), and the AuditKIT
  scores below are scores of RECORDED deterministic trajectories, not of a
  fine-tuned model.
- No live model call: AuditKIT runs in ``recorded`` mode only (AG-06: no
  agent call). The "judge" scorers that need a model are not used.
- Parameterised queries record the SQL template (with ``?`` placeholders)
  in the trajectory arguments; the bound parameter values are not recorded
  separately. The observation (returned rows) is the executed query's real
  result, so nothing is faked — but a reviewer re-running the trajectory
  needs the task text to recover the parameters, as documented here.

Run:  python3 -m prototype.auditkit_eval   (from ~/workspace/lexsi-hackathon/,
        with the project .venv active)
Writes: outputs/trajectories.jsonl, outputs/auditkit_eval.json
"""
from __future__ import annotations

import json
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))

from agent import run_agent  # noqa: E402
from db import open_db  # noqa: E402
from tasks import TASKS  # noqa: E402

VARIANTS = ("base", "improved")

# The documented minimal correct tool route for every task in this set:
# inspect the schema, then run one question-specific read-only query.
# (The improved agent follows it; the base agent skips describe_table and
# runs a generic dump instead, which is exactly what the F1 scorer measures.)
GOLD_ROUTE = [[{"name": "list_tables", "arguments": {}}],
              [{"name": "describe_table", "arguments": {"table": "orders"}}],
              [{"name": "run_query", "arguments": {}}]]

ALLOWED_TOOLS = ["list_tables", "describe_table", "run_query"]

# Reference-free scorers plus name-only tool-call F1 against GOLD_ROUTE.
# Arg-sensitive scorers are deliberately NOT used: the gold route names the
# correct tools, not the exact SQL text, so comparing arguments against it
# would be circular (the SQL is generated by the agent under test).
SCORERS = ["tool_call_f1_name", "tool_call_validity", "redundant_tool_calls",
           "agent_loop_detection", "tool_permission"]


def _tool_arguments(tool: str, args: tuple) -> dict:
    """Tool-call arguments as recorded in the trajectory.

    ``describe_table`` records its table; ``run_query`` records the SQL
    template (parameter values are NOT recorded — see module docstring).
    """
    if tool == "describe_table":
        return {"table": args[0] if args else ""}
    if tool == "run_query":
        return {"sql": args[0] if args else ""}
    return {}


def _observation(tool: str, result, rows: list[dict]) -> str:
    if tool == "list_tables":
        return "tables: " + ", ".join(result)
    if tool == "describe_table":
        return "columns: " + ", ".join(result)
    if tool == "run_query":
        return f"{len(rows)} row(s): " + json.dumps(rows, default=str)[:2000]
    return str(result)


def build_trajectories() -> list[dict]:
    """Run both variants on all tasks; return AgentTune Trajectory dicts."""
    from agenttune.agentic.trajectory.dataset import Step, Trajectory

    conn = open_db()
    records = []
    for task in TASKS:
        for variant in VARIANTS:
            result = run_agent(conn, task["question"], variant)
            correct = all(s in result.answer for s in task["must_contain"])
            steps = []
            for i, (tool, args) in enumerate(result.tool_calls):
                # Observation for each step: the tool's real return value.
                if tool == "list_tables":
                    obs_value: object = sorted({"customers", "products", "orders"})
                elif tool == "describe_table":
                    from agent import describe_table
                    obs_value = describe_table(args[0] if args else "")
                else:  # run_query — rows from THIS call (the final SQL's rows
                    # are result.rows; earlier calls share the same query here
                    # because each variant issues exactly one run_query).
                    obs_value = result.rows
                # One distinct, plain-language description per step. (Earlier
                # templated wording made two consecutive step descriptions
                # near-identical, which AuditKIT's loop detector — correctly,
                # given the text it saw — flagged as "reasoning stagnation".
                # The steps themselves never repeat a call; the descriptions
                # now say what each different step actually does.)
                if tool == "list_tables":
                    thought = "Inspect the database schema: list the available tables."
                elif tool == "describe_table":
                    thought = ("Look up the columns of the orders table so the "
                               "query references real columns.")
                elif result.checks.get("question_specific_query"):
                    thought = ("Execute the question-specific read-only query "
                               "and read back the result rows.")
                else:
                    thought = ("Fetch a broad dump of the orders table and "
                               "answer from that dump.")
                steps.append(Step(
                    step_number=i,
                    state=f"after {tool}",
                    action={"name": tool, "arguments": _tool_arguments(tool, args)},
                    observation=_observation(tool, obs_value,
                                             result.rows if tool == "run_query" else []),
                    thought=thought,
                    reward=1.0 if correct else 0.0,
                ))
            traj = Trajectory(
                task=task["question"],
                steps=steps,
                reward=1.0 if correct else 0.0,
                trajectory_id=f"{task['id']}-{variant}",
                final_response=result.answer,
                metadata={
                    "task_id": task["id"],
                    "variant": variant,
                    "correct": correct,
                    "tool_call_count": len(result.tool_calls),
                    "expected": task["expected"],
                    "must_contain": list(task["must_contain"]),
                    "source": "dataagent-deterministic-run",
                },
            )
            records.append(traj.to_dict())
    return records


def write_trajectories(path: str) -> list[dict]:
    records = build_trajectories()
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        for rec in records:
            f.write(json.dumps(rec) + "\n")
    return records


def _must_contain_predicate(episode, case) -> bool:
    """Outcome oracle: the final answer contains every must_contain string.

    Identical rule to the existing harness (prototype/eval.py), so the
    AuditKIT outcome and the harness task_accuracy agree by construction.
    """
    must = (case.metadata or {}).get("must_contain") or []
    answer = getattr(episode, "final_answer", None) or ""
    return all(s in answer for s in must)


def run_auditkit(trajectories_path: str) -> dict:
    """Score the recorded trajectories with real AuditKIT; return JSON-able results."""
    from auditkit.agent_eval import (
        AgentCase, AgentEvalRunner, AgentEvalSpec, CustomPredicate,
    )

    cases = []
    for task in TASKS:
        for variant in VARIANTS:
            cases.append(AgentCase(
                id=f"{task['id']}-{variant}",
                task=task["question"],
                category="database-agent",
                allowed_tools=list(ALLOWED_TOOLS),
                budgets={"max_tool_calls": 5},
                outcome=CustomPredicate(_must_contain_predicate,
                                        version="dataagent-must-contain/1",
                                        name="must_contain"),
                reference_turns=[list(turn) for turn in GOLD_ROUTE],
                metadata={"must_contain": list(task["must_contain"]),
                          "variant": variant, "task_id": task["id"]},
            ))
    spec = AgentEvalSpec(cases=cases, mode="recorded",
                         import_path=trajectories_path,
                         scorers=list(SCORERS),
                         name="dataagent-auditkit-recorded")
    result = AgentEvalRunner().run(spec)
    rows = [row.to_dict() for row in result.rows]
    summary = {}
    raw_summary = getattr(result, "summary", None)
    try:
        summary = raw_summary() if callable(raw_summary) else raw_summary
        if not isinstance(summary, dict):
            summary = {"summary": summary}
    except Exception as e:  # summary is a convenience, not the result
        summary = {"summary_error": str(e)}
    return {"mode": "recorded", "scorers": list(SCORERS),
            "n_cases": len(rows), "rows": rows, "summary": summary}


def main() -> None:
    here = os.path.dirname(os.path.abspath(__file__))
    root = os.path.dirname(here)
    traj_path = os.path.join(root, "outputs", "trajectories.jsonl")
    out_path = os.path.join(root, "outputs", "auditkit_eval.json")

    records = write_trajectories(traj_path)
    print(f"trajectories: {len(records)} records -> {traj_path}")
    eval_out = run_auditkit(traj_path)
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(eval_out, f, indent=2)
    print(f"auditkit eval: {eval_out['n_cases']} cases -> {out_path}")
    for row in eval_out["rows"]:
        outcome = row.get("outcome", {})
        diag = row.get("diagnostics", {})
        print(f"{row['case_id']}: verdict={outcome.get('verdict')} "
              f"status={row.get('status')} diagnostics={json.dumps(diag)[:400]}")


if __name__ == "__main__":
    main()
